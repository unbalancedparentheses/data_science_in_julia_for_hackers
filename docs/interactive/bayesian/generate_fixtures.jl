# Run with --project=17_bayesian_workflow from the repository root.
include(joinpath(@__DIR__, "../../../17_bayesian_workflow/core.jl"))
using .FootballWorkflow, Distributions, Statistics
json(x::Number) = string(x)
json(x::AbstractArray) = "[" * join(json.(x), ",") * "]"
goals = football_data().goals
rows = String[]
for strength in (.5,1.,5.,10.,30.), posterior in (false,true)
 a = 2strength + (posterior ? sum(goals) : 0)
 b = strength + (posterior ? length(goals) : 0)
 predictive = NegativeBinomial(a,b/(b+1))
 probabilities = vcat(pdf.(Ref(predictive),0:10),ccdf(predictive,10))
 push!(rows,"{\"strength\":$strength,\"posterior\":$posterior,\"shape\":$a,\"rate\":$b,\"mean\":$(mean(predictive)),\"variance\":$(var(predictive)),\"probabilities\":$(json(probabilities))}")
end
payload="{\"goals\":$(json(goals)),\"expected\":[$(join(rows,","))]}"
write(isempty(ARGS) ? joinpath(@__DIR__,"fixtures.js") : only(ARGS),"// Generated by generate_fixtures.jl using Distributions.jl, not browser calculations.\nconst bayesianFixture = " * payload * ";\nif(typeof module !== 'undefined') module.exports = bayesianFixture;\n")
