# Small serializer for these numeric fixtures; no additional Julia packages.
fixture_json(x::Real) = isfinite(x) ? string(x) : error("nonfinite fixture")
fixture_json(x::AbstractString) = "\"" * replace(x, "\\"=>"\\\\", "\""=>"\\\"", "\n"=>"\\n") * "\""
fixture_json(x::NamedTuple) = "{" * join([fixture_json(string(k))*":"*fixture_json(v) for (k,v) in pairs(x)], ",") * "}"
fixture_json(x::AbstractVector) = "[" * join(fixture_json.(x), ",") * "]"
function write_fixture(data, default_path)
    path = isempty(ARGS) ? default_path : only(ARGS)
    write(path, "// Generated by Julia; see generate_fixture.jl.\nexport default " * fixture_json(data) * ";\n")
    println("Wrote ", path)
end
